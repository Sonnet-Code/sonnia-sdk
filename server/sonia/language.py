"""The language Sonnia speaks and writes (``LANGUAGE``).

The prompts are written once, in English, and only told which language to answer in
(:attr:`Language.name`). What visitors read on the screen is not generated by a model, so
it is written once per language, in ``assets/languages/<code>.json``:

    {
      "name": "Spanish",            # in English: what the models are told
      "native_name": "Español",
      "texts": {"invitation": "¡Acércate y pregúntame\\nlo que quieras!", ...},
      "dates": {"format": "{weekday} {day} de {month}",
                "weekdays": ["lunes", ...], "months": ["enero", ...]}
    }

``en.json`` is the reference: every other file has exactly its keys and the same
``{placeholders}`` in each text (a test checks the bundled ones; :func:`load_language`
fills a missing text with the English one and logs it). The orchestrator uses a few of
the texts itself (the waiting pill, the away sign) and sends all of them to the avatar
client in the sticky ``screen_texts`` message. ``dates`` (optional; English if missing or
wrong) writes a day on the screen, as on the talk card of ``show_talk``.

To add a language, copy ``en.json`` to ``<code>.json`` (a short code such as ``it``),
translate the texts and set ``LANGUAGE=<code>``. A folder ``languages`` in ``ASSETS_DIR``
is searched before the bundled one, so a language can also be added or changed without
touching the program.
"""

from __future__ import annotations

import json
import logging
import re
from collections.abc import Mapping, Sequence
from dataclasses import dataclass, field
from datetime import date
from pathlib import Path

from sonia.paths import BUNDLE_ROOT

__all__ = [
    "BUNDLED_LANGUAGES_DIR",
    "DEFAULT_LANGUAGE",
    "DateWords",
    "Language",
    "LanguageError",
    "available_languages",
    "describe_languages",
    "language_dirs",
    "load_language",
    "read_dates",
    "read_language_file",
    "text_placeholders",
]

logger = logging.getLogger(__name__)

BUNDLED_LANGUAGES_DIR = BUNDLE_ROOT / "assets" / "languages"

#: The reference language: its file has every key, and it fills any gap.
DEFAULT_LANGUAGE = "en"

_CODE = re.compile(r"^[a-z]{2,3}(-[A-Za-z0-9]{2,8})*$")
_PLACEHOLDER = re.compile(r"\{([A-Za-z_][A-Za-z0-9_]*)\}")


class LanguageError(ValueError):
    """A language file that cannot be used."""


def text_placeholders(text: str) -> set[str]:
    """The ``{name}`` placeholders of a screen text."""
    return set(_PLACEHOLDER.findall(text))


#: The placeholders a date format has (all three, each once or more).
DATE_PLACEHOLDERS = frozenset({"weekday", "day", "month"})


@dataclass(frozen=True, slots=True)
class DateWords:
    """How a language writes a day: ``Friday 20 November``, ``viernes 20 de noviembre``."""

    format: str = "{weekday} {day} {month}"
    #: Monday first.
    weekdays: tuple[str, ...] = (
        "Monday",
        "Tuesday",
        "Wednesday",
        "Thursday",
        "Friday",
        "Saturday",
        "Sunday",
    )
    months: tuple[str, ...] = (
        "January",
        "February",
        "March",
        "April",
        "May",
        "June",
        "July",
        "August",
        "September",
        "October",
        "November",
        "December",
    )

    def write(self, day: date) -> str:
        return (
            self.format.replace("{weekday}", self.weekdays[day.weekday()])
            .replace("{day}", str(day.day))
            .replace("{month}", self.months[day.month - 1])
        )


@dataclass(frozen=True, slots=True)
class Language:
    """A language: its name for the models and its screen texts."""

    #: ``LANGUAGE``: ``en``, ``es``...
    code: str
    #: In English, as the models are told: "Spanish".
    name: str
    #: As its speakers write it: "Español".
    native_name: str
    #: Screen texts by key, complete (gaps filled with English).
    texts: Mapping[str, str] = field(default_factory=dict)
    dates: DateWords = field(default_factory=DateWords)

    def date(self, day: date) -> str:
        """``day`` as this language writes it on the screen."""
        return self.dates.write(day)

    def text(self, key: str, **values: object) -> str:
        """The text ``key`` with its ``{placeholders}`` replaced; empty if there is none
        (only with a broken install, without ``en.json``)."""
        out = self.texts.get(key, "")
        for name, value in values.items():
            out = out.replace("{" + name + "}", str(value))
        return out


def language_dirs(assets_dir: str | Path | None = None) -> list[Path]:
    """Where language files are looked for: ``ASSETS_DIR/languages``, then the bundled one."""
    dirs: list[Path] = []
    if assets_dir is not None:
        dirs.append(Path(assets_dir) / "languages")
    if BUNDLED_LANGUAGES_DIR not in dirs:
        dirs.append(BUNDLED_LANGUAGES_DIR)
    return dirs


def available_languages(assets_dir: str | Path | None = None) -> dict[str, Path]:
    """Every language code with a file, and the file used (the first folder wins)."""
    found: dict[str, Path] = {}
    for directory in reversed(language_dirs(assets_dir)):
        if directory.is_dir():
            for path in sorted(directory.glob("*.json")):
                if _CODE.match(path.stem):
                    found[path.stem] = path
    return dict(sorted(found.items()))


def read_language_file(path: Path) -> tuple[str, str, dict[str, str]]:
    """``(name, native_name, texts)`` of a language file. ``LanguageError`` if it is not one."""
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        raise LanguageError(f"{path}: cannot be read ({exc})") from exc
    if not isinstance(data, dict):
        raise LanguageError(f"{path}: expected a JSON object")
    name = data.get("name")
    if not isinstance(name, str) or not name.strip():
        raise LanguageError(f'{path}: "name" (the language in English) is missing')
    native = data.get("native_name")
    native = native.strip() if isinstance(native, str) and native.strip() else name.strip()
    texts = data.get("texts")
    if not isinstance(texts, dict):
        raise LanguageError(f'{path}: "texts" must be an object')
    clean = {str(k): v for k, v in texts.items() if isinstance(v, str) and v.strip()}
    return name.strip(), native, clean


def _words(value: object, count: int) -> tuple[str, ...] | None:
    if not isinstance(value, list) or len(value) != count:
        return None
    words = tuple(str(item).strip() for item in value)
    return words if all(words) else None


def read_dates(path: Path) -> DateWords | None:
    """The ``dates`` block of a language file; ``None`` if it has none or it is wrong (a
    format without ``{weekday}``, ``{day}`` and ``{month}``, not 7 weekdays or 12 months)."""
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None
    block = data.get("dates") if isinstance(data, dict) else None
    if not isinstance(block, dict):
        return None
    fmt = block.get("format")
    weekdays = _words(block.get("weekdays"), 7)
    months = _words(block.get("months"), 12)
    if (
        not isinstance(fmt, str)
        or text_placeholders(fmt) != DATE_PLACEHOLDERS
        or weekdays is None
        or months is None
    ):
        logger.warning(
            '%s: "dates" needs a "format" with {weekday}, {day} and {month}, 7 weekdays '
            "(Monday first) and 12 months; using English dates",
            path.name,
        )
        return None
    return DateWords(fmt, weekdays, months)


def load_language(code: str, assets_dir: str | Path | None = None) -> Language:
    """The language ``code``, complete. Never raises: an unknown code or a broken file
    falls back to English with a warning, and texts missing from a file are taken from
    English, so the screen always has something to show."""
    files = available_languages(assets_dir)
    reference = _reference(files)
    wanted = (code or DEFAULT_LANGUAGE).strip()
    path = files.get(wanted)
    if path is None:
        if wanted != DEFAULT_LANGUAGE:
            logger.warning(
                "There is no language file for LANGUAGE=%s (available: %s); using English",
                wanted,
                ", ".join(files) or "none",
            )
        return reference
    if wanted == DEFAULT_LANGUAGE:
        return reference
    try:
        name, native, texts = read_language_file(path)
    except LanguageError as exc:
        logger.warning("%s; using English", exc)
        return reference
    complete = dict(reference.texts)
    missing: list[str] = []
    for key, english in reference.texts.items():
        text = texts.get(key)
        if text is None:
            missing.append(key)
        elif text_placeholders(text) != text_placeholders(english):
            missing.append(key)
            logger.warning(
                "%s: %r needs exactly the placeholders of English: %s",
                path.name,
                key,
                ", ".join(sorted(text_placeholders(english))) or "none",
            )
        else:
            complete[key] = text
    if missing:
        logger.warning("%s: using English for %s", path.name, ", ".join(missing))
    return Language(
        code=wanted,
        name=name,
        native_name=native,
        texts=complete,
        dates=read_dates(path) or reference.dates,
    )


_FALLBACK_NAME = "English"


def _reference(files: Mapping[str, Path]) -> Language:
    """English, from its file; without one (a broken install), just the name."""
    path = files.get(DEFAULT_LANGUAGE)
    if path is not None:
        try:
            name, native, texts = read_language_file(path)
            return Language(DEFAULT_LANGUAGE, name, native, texts, read_dates(path) or DateWords())
        except LanguageError as exc:
            logger.error("%s", exc)
    return Language(DEFAULT_LANGUAGE, _FALLBACK_NAME, _FALLBACK_NAME, {})


def describe_languages(assets_dir: str | Path | None = None) -> Sequence[str]:
    """``code (Native name)`` for every available language, for messages and docs."""
    out: list[str] = []
    for code, path in available_languages(assets_dir).items():
        try:
            _, native, _ = read_language_file(path)
        except LanguageError:
            continue
        out.append(f"{code} ({native})")
    return out
