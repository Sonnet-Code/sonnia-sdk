// Avatar animation catalog.
//
// This file is the single source of truth: the motion set generator
// (Editor/SoniaMotionSetBuilder.cs) uses it to fill the SoniaMotionSet asset
// from the clips under Assets/Animations, and to decide which clips loop. To
// add a clip, touch only this file and run "Sonnia > Create Motion Set" again.
//
// Every clip is made by Genies for their skeleton and is redistributable (see
// Assets/Animations/Genies/LICENSE.md): Wave and Peace from the Genies Avatar
// Starter Pack, and the Apache-2.0 clips from the public GeniesIRL and
// GeniesCamera repositories. The idle loop (SonniaIdle) is generated by the
// same menu from a still frame of one of those clips, with a slow weight shift
// on top; breathing, head, face and eyes move procedurally.
//
// With the Genies Avatar SDK installed, the menu also copies the SDK's own
// common animations (DefaultIdle and Walk, under the SDK license) to
// Assets/Animations/GeniesSdk, which is not committed, and prefers them.
// Without a walk cycle the avatar slides off screen in away mode.

using UnityEngine;

namespace Sonia
{
    /// <summary>Family an idle attention animation belongs to.</summary>
    public enum AttentionCategory
    {
        /// <summary>A whole dance. The most eye-catching, used sparingly.</summary>
        Dance = 0,

        /// <summary>A gesture that breaks the fourth wall: waving or addressing whoever looks at the screen.</summary>
        FourthWall = 1,

        /// <summary>A soft filler gesture.</summary>
        Soft = 2
    }

    /// <summary>An attention animation: clip name and category.</summary>
    public sealed class AttentionClip
    {
        /// <summary>Clip name (and file name), without extension.</summary>
        public readonly string Name;

        /// <summary>Family used to share out probabilities.</summary>
        public readonly AttentionCategory Category;

        public AttentionClip(string name, AttentionCategory category)
        {
            Name = name;
            Category = category;
        }
    }

    /// <summary>Clip names and paths shared by the editor and the runtime.</summary>
    public static class SoniaAnimations
    {
        /// <summary>Redistributable clips from Genies (committed).</summary>
        public const string GeniesClipFolder = "Assets/Animations/Genies";

        /// <summary>Clips generated by "Sonnia > Create Motion Set" (committed).</summary>
        public const string GeneratedClipFolder = "Assets/Animations/Sonnia";

        /// <summary>
        /// Copies of the Genies Avatar SDK common animations, only when the SDK is
        /// installed. Not committed: they are under the SDK license.
        /// </summary>
        public const string SdkClipFolder = "Assets/Animations/GeniesSdk";

        /// <summary>Common animations inside the Genies Avatar SDK package.</summary>
        public const string SdkCommonAnimationsFolder =
            "Packages/com.genies.avatar-sdk.client/Internal/Avatars/Runtime/Assets/CommonAnimations";

        /// <summary>Folders with clips (.anim, or FBX with a clip of the same name), in lookup order.</summary>
        public static readonly string[] ClipFolders =
        {
            SdkClipFolder,
            GeniesClipFolder,
            GeneratedClipFolder
        };

        /// <summary>Asset generated by "Sonnia > Create Motion Set".</summary>
        public const string MotionSetPath = "Assets/Animations/SoniaMotionSet.asset";

        /// <summary>Upper body mask, generated with the set.</summary>
        public const string UpperBodyMaskPath = "Assets/Animations/SoniaUpperBody.mask";

        // ------------------------------------------------------------------
        // Generated idle loop
        // ------------------------------------------------------------------

        /// <summary>Idle loop generated from a still frame (see the header).</summary>
        public const string GeneratedIdleClip = "SonniaIdle";

        /// <summary>Clip whose frame gives the rest pose of <see cref="GeneratedIdleClip"/>.</summary>
        public const string GeneratedIdleSourceClip = "actions-presentItem_intro";

        /// <summary>Second of <see cref="GeneratedIdleSourceClip"/> sampled for the rest pose.</summary>
        public const float GeneratedIdleSourceTime = 0f;

        /// <summary>Common animations copied from the Genies Avatar SDK when it is installed.</summary>
        public static readonly string[] SdkClips = { "DefaultIdle", "Walk" };

        // ------------------------------------------------------------------
        // Clips per state
        // ------------------------------------------------------------------

        /// <summary>
        /// Base idle loop (also used to speak, which has no clips of its own), in
        /// order of preference: the Genies SDK idle when it is installed, then the
        /// generated one.
        /// </summary>
        public static readonly string[] IdleLoopClips = { "DefaultIdle", GeneratedIdleClip };

        /// <summary>One-shot idle variations. Genies publishes none.</summary>
        public static readonly string[] IdleVariationClips = new string[0];

        /// <summary>Listening loop: the same idle; AvatarStateController tilts and nods the head on top.</summary>
        public static readonly string[] ListeningLoopClips = IdleLoopClips;

        /// <summary>One-shot nods. Empty: AvatarStateController nods procedurally.</summary>
        public static readonly string[] NodClips = new string[0];

        /// <summary>
        /// Thinking loop: the same idle as idle and speaking, so going from
        /// thinking to speaking does not change clip (gaze and face do the rest).
        /// </summary>
        public static readonly string[] ThinkingLoopClips = IdleLoopClips;

        /// <summary>Thinking variations: looking at the hand as if examining something (GeniesIRL).</summary>
        public static readonly string[] ThinkingVariationClips = { "actions-0224-lookAtObject_Trimmed" };

        /// <summary>Gestures while speaking. Genies publishes none: speech starts from the idle.</summary>
        public static readonly string[] TalkingClips = new string[0];

        /// <summary>Wave to whoever comes closer (Starter Pack).</summary>
        public const string GreetingClip = "Wave";

        /// <summary>
        /// Gesture to present an image: the arm stretches towards the viewer with
        /// the palm up (GeniesIRL, presentItem_intro). It plays on the right arm
        /// layer and freezes at <see cref="PresentHoldTime"/> while the image is up.
        /// </summary>
        public const string PresentClip = "actions-presentItem_intro";

        /// <summary>Second of the present clip where the arm is already stretched.</summary>
        public const float PresentHoldTime = 1.0f;

        /// <summary>
        /// Walk cycle to leave and come back in away mode (Genies SDK only). It
        /// loops with the XZ motion out of the pose (center of mass):
        /// PresenceController reads that motion every frame and moves the avatar
        /// exactly what the feet give.
        /// </summary>
        public const string WalkClip = "Walk";

        /// <summary>
        /// Attention gestures the avatar plays on its own while idle, so the
        /// screen does not look like a statue. All of them play once.
        /// </summary>
        public static readonly AttentionClip[] AttentionClips =
        {
            new AttentionClip("QuickAction_vibe", AttentionCategory.Dance),
            new AttentionClip("Peace", AttentionCategory.FourthWall),
            new AttentionClip("QuickAction_salute", AttentionCategory.FourthWall),
            new AttentionClip("QuickAction_twoThumbsUp", AttentionCategory.FourthWall)
        };

        /// <summary>
        /// Trivia gestures (correct, wrong, encouragement). Empty: TriviaController
        /// uses the attention clips (see TriviaController.*Clip).
        /// </summary>
        public static readonly string[] TriviaClips = new string[0];

        /// <summary>
        /// Only the base loops (and the walk cycle) loop. Everything else plays
        /// once and ends: that is how the choreographer knows when to chain the
        /// next clip instead of cutting a gesture halfway.
        /// </summary>
        public static bool IsLoopingClip(string clipName)
        {
            return IsIdleLoop(clipName) || clipName == WalkClip;
        }

        /// <summary>
        /// Idle loops keep the horizontal motion inside the pose. Extracted as root
        /// motion (and discarded, with applyRootMotion off) the weight shift is
        /// lost: the hips stay pinned and the feet slide instead. Every other clip
        /// still extracts it: PresenceController reads the walk motion, and
        /// gestures and dances stay in place.
        /// </summary>
        public static bool KeepsHorizontalMotionInPose(string clipName)
        {
            return IsIdleLoop(clipName);
        }

        private static bool IsIdleLoop(string clipName)
        {
            return System.Array.IndexOf(IdleLoopClips, clipName) >= 0
                || System.Array.IndexOf(ListeningLoopClips, clipName) >= 0
                || System.Array.IndexOf(ThinkingLoopClips, clipName) >= 0;
        }
    }
}
